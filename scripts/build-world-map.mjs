async function main() {
  console.log('Fetching world land TopoJSON...');
  const topoRes = await fetch(LAND_URL);
  const topo = await topoRes.json();

  console.log('Converting to GeoJSON...');
  const geo = feature(topo, topo.objects.land);

  const MAP_W = 2000;
  const MAP_H = 1000;

  // Create projection fitted to the land GeoJSON
  const projection = geoNaturalEarth1();
  projection.fitSize([MAP_W, MAP_H], geo);

  console.log('Generating SVG paths...');
  const pathGen = geoPath(projection);
  const paths = geo.features.map(f => {
    const p = pathGen(f);
    return p || '';
  }).filter(p => p && p.length > 10);

  console.log(`Generated ${paths.length} paths`);

  // Generate graticule lines
  console.log('Generating graticule lines...');
  const vertical = [];
  for (let lon = -180; lon <= 180; lon += 30) {
    const [x1, y1] = projection([lon, -90]);
    const [x2, y2] = projection([lon, 90]);
    vertical.push([
      Math.round(x1 * 10) / 10,
      Math.round(y1 * 10) / 10,
      Math.round(x2 * 10) / 10,
      Math.round(y2 * 10) / 10,
    ]);
  }

  const horizontal = [];
  for (let lat = -60; lat <= 60; lat += 30) {
    const [x1, y1] = projection([-180, lat]);
    const [x2, y2] = projection([180, lat]);
    horizontal.push([
      Math.round(x1 * 10) / 10,
      Math.round(y1 * 10) / 10,
      Math.round(x2 * 10) / 10,
      Math.round(y2 * 10) / 10,
    ]);
  }

  // Generate country markers
  console.log('Generating country markers...');
  const markers = {};
  for (const [id, [lon, lat]] of Object.entries(COUNTRY_CENTERS)) {
    const [x, y] = projection([lon, lat]);
    markers[id] = {
      x: Math.round(x * 10) / 10,
      y: Math.round(y * 10) / 10,
    };
  }

  // Verify some markers are in reasonable positions
  console.log('Sample markers:');
  for (const id of ['cn', 'us', 'gb', 'au', 'br', 'jp']) {
    console.log(`  ${id}: ${JSON.stringify(markers[id])}`);
  }

  const output = `// Auto-generated world map data
// Source: Natural Earth 110m land data via world-atlas
// Projection: Natural Earth, fitted to ${MAP_W}×${MAP_H} viewBox
// This file is generated by scripts/build-world-map.mjs

export const MAP_W = ${MAP_W};
export const MAP_H = ${MAP_H};

// Land polygon SVG paths (Natural Earth projection)
// Higher precision than the original hand-drawn lat/lng polygons
export const CONTINENTS: string[] = ${JSON.stringify(paths)};

// Pre-computed graticule (grid) lines in Natural Earth projection
export const GRATICULE: {
  vertical: [number, number, number, number][];
  horizontal: [number, number, number, number][];
} = {
  vertical: ${JSON.stringify(vertical)},
  horizontal: ${JSON.stringify(horizontal)},
};

// Pre-computed country marker positions in SVG coordinates
export const COUNTRY_MARKERS: Record<string, { x: number; y: number }> = ${JSON.stringify(markers)};

// Get marker position for a country
export function getMarker(countryId: string): { x: number; y: number } {
  return COUNTRY_MARKERS[countryId] ?? { x: ${(MAP_W / 2).toFixed(1)}, y: ${(MAP_H / 2).toFixed(1)} };
}
`;

  const outPath = path.join(process.cwd(), 'src', 'data', 'worldMap.ts');
  fs.writeFileSync(outPath, output);
  console.log(`\nWritten to ${outPath}`);
  const stats = fs.statSync(outPath);
  console.log(`File size: ${(stats.size / 1024).toFixed(1)} KB`);
}

main().catch(console.error);
