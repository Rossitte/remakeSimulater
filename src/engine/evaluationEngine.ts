function pickRandom<T>(arr: T[]): T {
  return arr[randomInt(0, arr.length - 1)];
}

/** 根据数值返回对应的评语池等级 */
function getTier(value: number, tiers: [number, number, number, number]): string {
  const [t1, t2, t3, t4] = tiers;
  if (value >= t1) return 'great';
  if (value >= t2) return 'good';
  if (value >= t3) return 'normal';
  if (value >= t4) return 'tough';
  return 'tough';
}

